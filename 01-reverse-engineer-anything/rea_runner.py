"""
Reverse Engineer Anything (REA) - Clean-Room Extraction & Reconstruction Harness
Automates structural extraction of web apps, Electron bundles, and APIs into clean-room schemas.
"""

import json
import os
import re
import sys
from dataclasses import dataclass, asdict
from typing import List, Dict, Any

@dataclass
class EndpointContract:
    path: str
    method: str
    params: List[str]
    sample_response: Dict[str, Any]

@dataclass
class UIComponentSpec:
    name: str
    state_variables: List[str]
    props: List[str]
    actions: List[str]

@dataclass
class CleanRoomManifest:
    target_name: str
    extracted_version: str
    endpoints: List[EndpointContract]
    components: List[UIComponentSpec]
    recommended_stack: Dict[str, str]

def extract_endpoints_from_traffic_or_bundle(raw_text: str) -> List[EndpointContract]:
    """
    Extracts HTTP paths, methods, and payload structures from HAR, network logs, or JS bundle text.
    """
    url_pattern = re.compile(r'["\'](/(?:api|v[0-9]+)/[a-zA-Z0-9_\-/]+)["\']')
    found_paths = sorted(list(set(url_pattern.findall(raw_text))))
    
    contracts = []
    for path in found_paths:
        # Determine likely method and fields from path structure
        method = "POST" if any(verb in path for verb in ["create", "update", "submit", "login", "send"]) else "GET"
        contracts.append(EndpointContract(
            path=path,
            method=method,
            params=["id", "payload", "filter"] if method == "POST" else ["page", "limit", "query"],
            sample_response={"status": "success", "data": {}, "timestamp": "2026-10-16T00:00:00Z"}
        ))
    return contracts

def extract_component_contracts(component_names: List[str]) -> List[UIComponentSpec]:
    """
    Synthesizes clean-room interface contracts for primary UI modules.
    """
    specs = []
    for name in component_names:
        specs.append(UIComponentSpec(
            name=name,
            state_variables=["isLoading", "data", "error", "selectedItemId"],
            props=["title", "onAction", "theme"],
            actions=["handleSelect", "handleSubmit", "handleReset"]
        ))
    return specs

def generate_openapi_spec(manifest: CleanRoomManifest) -> Dict[str, Any]:
    """
    Generates a valid OpenAPI 3.1.0 specification from extracted contracts.
    """
    paths_dict = {}
    for ep in manifest.endpoints:
        paths_dict[ep.path] = {
            ep.method.lower(): {
                "summary": f"Clean-room replacement for {ep.path}",
                "parameters": [{"name": p, "in": "query", "schema": {"type": "string"}} for p in ep.params],
                "responses": {
                    "200": {
                        "description": "Successful response",
                        "content": {
                            "application/json": {
                                "schema": {
                                    "type": "object",
                                    "properties": {
                                        "status": {"type": "string"},
                                        "data": {"type": "object"}
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    
    return {
        "openapi": "3.1.0",
        "info": {
            "title": f"{manifest.target_name} Clean-Room API Specification",
            "version": manifest.extracted_version,
            "description": "Automatically generated by REA clean-room extraction engine."
        },
        "paths": paths_dict
    }

def main():
    print("[+] REA Clean-Room Extraction Harness Initialized.")
    sample_bundle_analysis = """
    fetch('/api/v1/workspaces', { method: 'GET' });
    fetch('/api/v1/workspaces/create', { method: 'POST', body: JSON.stringify(data) });
    fetch('/api/v1/auth/session', { method: 'GET' });
    fetch('/api/v1/analytics/telemetry', { method: 'POST' });
    fetch('/api/v1/projects/export', { method: 'POST' });
    """
    
    endpoints = extract_endpoints_from_traffic_or_bundle(sample_bundle_analysis)
    components = extract_component_contracts(["WorkspaceDashboard", "ProjectCanvas", "ExportModal", "TelemetryHUD"])
    
    manifest = CleanRoomManifest(
        target_name="AutonomousWorkspaceSuite",
        extracted_version="1.0.0",
        endpoints=endpoints,
        components=components,
        recommended_stack={
            "frontend": "Next.js 15 / React 19 / TailwindCSS v4",
            "backend": "FastAPI / Python 3.12 / Pydantic v2",
            "database": "PostgreSQL + pgvector",
            "mcp": "FastMCP Server"
        }
    )
    
    openapi = generate_openapi_spec(manifest)
    
    out_dir = os.path.dirname(__file__)
    spec_path = os.path.join(out_dir, "clean_room_openapi.json")
    with open(spec_path, "w", encoding="utf-8") as f:
        json.dump(openapi, f, indent=2)
        
    print(f"[✓] Extracted {len(endpoints)} endpoint contracts and {len(components)} component specs.")
    print(f"[✓] Saved clean-room OpenAPI specification to: {spec_path}")

if __name__ == "__main__":
    main()
